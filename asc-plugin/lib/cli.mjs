import { AscError, AscClient } from './client.mjs';
import { loadConfig, requireCredentials } from './config.mjs';
import { color, UserError } from './util.mjs';
import meta from './commands/meta.mjs';
import provisioning from './commands/provisioning.mjs';
import store from './commands/store.mjs';
import builds from './commands/builds.mjs';
import testflight from './commands/testflight.mjs';
import readiness from './commands/readiness.mjs';

export const COMMANDS = [...readiness, ...meta, ...builds, ...testflight, ...store, ...provisioning];

const GLOBAL_OPTIONS = [
  ['--app <id|bundleId|name>', 'Target app (default: .asc.json "app", env ASC_APP)'],
  ['--platform <ios|macos|tvos|visionos>', 'Platform scope (default: .asc.json "platform", else ios)'],
  ['--json', 'Machine-readable output'],
  ['--verbose', 'Log every API request to stderr'],
  ['--key-path / --key-id / --issuer', 'Override credentials for this call'],
];
const GLOBAL_BOOLS = new Set(['json', 'verbose', 'help']);

export function parseArgs(argv) {
  const bools = new Set([...GLOBAL_BOOLS, ...COMMANDS.flatMap((c) => c.bool ?? [])]);
  const positional = [];
  const flags = {};
  const set = (k, v) => {
    if (k in flags) flags[k] = [].concat(flags[k], v);
    else flags[k] = v;
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-h') flags.help = true;
    else if (a.startsWith('--')) {
      let [k, v] = a.slice(2).split(/=(.*)/s, 2);
      if (v === undefined && k.startsWith('no-') && bools.has(k.slice(3))) set(k.slice(3), false);
      else if (v !== undefined) set(k, v);
      else if (bools.has(k)) set(k, true);
      else if (i + 1 < argv.length && !(argv[i + 1].startsWith('--'))) set(k, argv[++i]);
      else set(k, true);
    } else positional.push(a);
  }
  return { positional, flags };
}

export function findCommand(positional) {
  for (let n = Math.min(3, positional.length); n >= 1; n--) {
    const name = positional.slice(0, n).join(' ');
    const cmd = COMMANDS.find((c) => c.name === name);
    if (cmd) return { cmd, args: positional.slice(n) };
  }
  return null;
}

const group = (c) => c.name.split(' ')[0];

export function helpText(filter) {
  if (filter) {
    const hits = COMMANDS.filter((c) => c.name === filter || group(c) === filter);
    if (!hits.length) return `No command "${filter}". Run \`asc help\`.`;
    return hits.map(commandHelp).join('\n\n');
  }
  const groups = [...new Set(COMMANDS.map(group))];
  const lines = [`${color.bold('asc')} — App Store Connect from the command line\n`, 'Usage: asc <command> [args] [--flags]   |   asc help <command|group>\n'];
  for (const g of groups) {
    lines.push(color.bold(g));
    for (const c of COMMANDS.filter((x) => group(x) === g)) lines.push(`  ${c.name.padEnd(26)} ${c.summary.split('. ')[0].replace(/\.$/, '')}`);
    lines.push('');
  }
  lines.push(color.bold('Global options'), ...GLOBAL_OPTIONS.map(([f, d]) => `  ${f.padEnd(40)} ${d}`));
  return lines.join('\n');
}

function commandHelp(c) {
  const out = [`${color.bold('asc ' + c.name)} — ${c.summary}`, `  Usage: ${c.usage ?? 'asc ' + c.name}`];
  for (const [f, d] of c.options ?? []) out.push(`    ${f.padEnd(34)} ${d}`);
  for (const e of c.examples ?? []) out.push(`  e.g. ${e}`);
  return out.join('\n');
}

/** Markdown reference generated from the registry so docs can never drift from the code. */
export function markdownDocs() {
  const out = ['# Command reference', '', '> Generated by `asc docs` — do not edit by hand.', '', '## Global options', '', '| Option | Description |', '|---|---|', ...GLOBAL_OPTIONS.map(([f, d]) => `| \`${f}\` | ${d} |`), ''];
  const groups = [...new Set(COMMANDS.map(group))];
  out.push('## Index', '', ...groups.map((g) => `- [${g}](#${g})`), '');
  for (const g of groups) {
    out.push(`## ${g}`, '');
    for (const c of COMMANDS.filter((x) => group(x) === g)) {
      out.push(`### \`asc ${c.name}\``, '', c.summary, '', '```', c.usage ?? `asc ${c.name}`, '```', '');
      if (c.options?.length) out.push('| Option | Description |', '|---|---|', ...c.options.map(([f, d]) => `| \`${f}\` | ${d} |`), '');
      if (c.examples?.length) out.push('Examples:', '', '```sh', ...c.examples, '```', '');
    }
  }
  return out.join('\n');
}

export async function main(argv) {
  const { positional, flags } = parseArgs(argv);
  try {
    if (!positional.length || positional[0] === 'help' || (flags.help && !findCommand(positional))) {
      console.log(helpText(positional[0] === 'help' ? positional.slice(1).join(' ') : undefined));
      return;
    }
    if (positional[0] === 'docs') return console.log(markdownDocs());
    if (positional[0] === 'commands') return console.log(COMMANDS.map((c) => c.name).join('\n'));
    const found = findCommand(positional);
    if (!found) throw new UserError(`Unknown command "${positional.join(' ')}". Run \`asc help\`.`);
    if (flags.help) return console.log(commandHelp(found.cmd));

    const cfg = loadConfig(flags);
    const ctx = { args: found.args, flags, cfg };
    if (!found.cmd.noAuth) {
      requireCredentials(cfg);
      ctx.client = new AscClient({ keyId: cfg.keyId, issuerId: cfg.issuerId, keyPath: cfg.keyPath, verbose: !!flags.verbose });
    }
    await found.cmd.run(ctx);
  } catch (e) {
    if (e instanceof UserError || e instanceof AscError) console.error(`${color.red('error:')} ${e.message}`);
    else console.error(flags.verbose ? e.stack : `${color.red('error:')} ${e.message}`);
    process.exitCode = 1;
  }
}
